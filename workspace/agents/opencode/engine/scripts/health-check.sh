#!/usr/bin/env bash
# shellcheck disable=SC2086
#
# health-check.sh — Periodic Health Check (G23)
#
# Verifies the entire toolkit is healthy. Runs targeted checks against scripts,
#
# Usage:
#   ./scripts/health-check.sh                           # All checks (default)
#   ./scripts/health-check.sh --check scripts           # Scripts only
#   ./scripts/health-check.sh --check contract           # Contract files only
#   ./scripts/health-check.sh --check rules              # Rules only
#   ./scripts/health-check.sh --check deps               # Dependencies only
#   ./scripts/health-check.sh --check index              # lean-ctx index only
#   ./scripts/health-check.sh --check docs               # Doc style only
#   ./scripts/health-check.sh --fix                      # Auto-fix minor issues
#   ./scripts/health-check.sh --verbose                  # Detailed output
#   ./scripts/health-check.sh --output json              # Machine-readable JSON
#   ./scripts/health-check.sh --help                     # Show this message
#
# Exit codes:
#   0 — All healthy
#   1 — Warnings (non-critical issues)
#   2 — Critical failures
#
# Requirements:
#   - bash 4+
#   - jq (for JSON validation and parsing)
#   - bc, python3 (optional, used by contract checks)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# shellcheck source=lib/paths.sh
. "$SCRIPT_DIR/lib/paths.sh"
PROJECT_ROOT="$(resolve_project_root "$PROJECT_DIR")"
SESSION_DIR="$(resolve_session_dir "$PROJECT_ROOT")"

# ── Config ──────────────────────────────────────────────────────────────────
VERBOSE=false
DO_FIX=false
OUTPUT_MODE="plain"   # plain or json
CHECK_MODE="all"      # all, scripts, contract, rules, references, docs, deps, index
EXIT_CODE=0
HAS_WARNINGS=false
HAS_CRITICAL=false

# ── Known scripts list — generated by scanning scripts/ ─────────────────────
CHECK_SCRIPTS=()
while IFS= read -r -d '' script; do
    CHECK_SCRIPTS+=("$(basename "$script")")
done < <(find "$SCRIPT_DIR" -maxdepth 1 -name '*.sh' -print0 2>/dev/null || true)

# ── Critical files to verify existence ──────────────────────────────────────
CRITICAL_FILES=(
    "contract/contract.template.json"
    "contract/contract.schema.json"
    "rules/rules.json"
    "agent.md"
    "README.md"
)

# ── Colors ──────────────────────────────────────────────────────────────────
if [[ -t 1 ]]; then
    RED='\033[0;31m'
    GREEN='\033[0;32m'
    YELLOW='\033[1;33m'
    CYAN='\033[0;36m'
    BOLD='\033[1m'
    NC='\033[0m'
else
    RED=''; GREEN=''; YELLOW=''; CYAN=''; BOLD=''; NC=''
fi

# ── Help ────────────────────────────────────────────────────────────────────
usage() {
    cat <<'USAGE'
health-check.sh — Periodic Health Check (G23)

SYNOPSIS
    ./scripts/health-check.sh [OPTIONS]

OPTIONS
    --help              Show this help message and exit
    --check TYPE        Run specific check type: scripts|contract|rules|references|docs|deps|index
    --check-all         Run all checks (default)
    --fix               Auto-fix minor issues (re-index lean-ctx if stale, re-create missing dirs)
    --verbose           Show details per check
    --output FORMAT     Output format: plain (default) or json

CHECK TYPES
    scripts     Verify all scripts in scripts/ exist and are executable
    contract    Verify contract files exist and are valid JSON
    rules       Verify rules.json is valid and has required keys
    references  Cross-reference integrity (doc/health-check.md lens 4 — Agent Doc References)
    docs        Doc style gate (em/en dashes, AI vocabulary, placeholders) via scripts/check-doc-style.sh
    session     Verify session state
    deps        Check required dependencies (jq, bc, python3)
    index       Check lean-ctx index freshness

FIX ACTIONS
    --fix enables auto-repair for:
    - Re-index lean-ctx if stale (>1 hour old or after code changes)
    - Re-create missing session/ directories
    - Set executable bit on scripts

EXIT CODES
    0   All healthy
    1   Warnings (non-critical issues)
    2   Critical failures

OUTPUT
    Results are written to session/health.json for audit trail

EXAMPLES
    ./scripts/health-check.sh
    ./scripts/health-check.sh --check deps
    ./scripts/health-check.sh --check all --fix --verbose
    ./scripts/health-check.sh --output json
