    exit 0
}

# ── Logging ─────────────────────────────────────────────────────────────────
log_pass() { local msg="$1"; if [[ "$OUTPUT_MODE" == "json" ]]; then echo "[PASS] $msg" >&2; else echo -e "  ${GREEN}[PASS]${NC} $msg"; fi; }
log_fail() { local msg="$1"; HAS_CRITICAL=true; if [[ "$OUTPUT_MODE" == "json" ]]; then echo "[FAIL] $msg" >&2; else echo -e "  ${RED}[FAIL]${NC} $msg"; fi; }
log_warn() { local msg="$1"; HAS_WARNINGS=true; if [[ "$OUTPUT_MODE" == "json" ]]; then echo "[WARN] $msg" >&2; else echo -e "  ${YELLOW}[WARN]${NC} $msg"; fi; }
log_info() { local msg="$1"; if [[ "$VERBOSE" == true ]]; then if [[ "$OUTPUT_MODE" == "json" ]]; then echo "[INFO] $msg" >&2; else echo -e "  ${CYAN}[INFO]${NC} $msg"; fi; fi; }
log_verbose() { local msg="$1"; if [[ "$VERBOSE" == true ]]; then if [[ "$OUTPUT_MODE" == "json" ]]; then echo "  :: $msg" >&2; else echo "  :: $msg"; fi; fi; }
log_dry() { local msg="$1"; if [[ "$OUTPUT_MODE" == "json" ]]; then echo "[DRY-RUN] $msg" >&2; else echo -e "  ${CYAN}[DRY-RUN]${NC} $msg"; fi; }
log_section() { local msg="$1"; if [[ "$OUTPUT_MODE" == "json" ]]; then echo "== $msg" >&2; else echo -e "\n${BOLD}==${NC} ${BOLD}$msg${NC}"; fi; }

# ── Helpers ─────────────────────────────────────────────────────────────────
get_session() { echo session 2>/dev/null || echo "unknown"; }
get_timestamp() { date -u +"%Y-%m-%dT%H:%M:%SZ"; }
is_executable() { [[ -x "$1" ]] && return 0 || return 1; }

check_dep() {
    local name="$1" binary="$2" optional="${3:-false}"
    if command -v "$binary" &>/dev/null; then log_pass "Dependency '$name' ($binary) found"; return 0
    else
        if [[ "$optional" == "true" ]]; then log_info "Dependency '$name' ($binary) not found (optional; no action needed)"; return 0
        else log_fail "Dependency '$name' ($binary) not found"; return 1; fi
    fi
}

# ── Check: Scripts ──────────────────────────────────────────────────────────
check_scripts() {
    local total=0 missing=0 not_exec=0
    log_section "Check: Scripts"
    if [[ ${#CHECK_SCRIPTS[@]} -eq 0 ]]; then log_fail "No scripts found in scripts/"; return 1; fi
    for script in "${CHECK_SCRIPTS[@]}"; do
        total=$((total + 1))
        local fp="$SCRIPT_DIR/$script"
        if [[ ! -f "$fp" ]]; then log_fail "Script missing: $script"; missing=$((missing + 1)); continue; fi
        if ! is_executable "$fp"; then log_warn "Script not executable: $script"; not_exec=$((not_exec + 1)); fi
        log_verbose "Found: $script ($(wc -l < "$fp") lines)"
    done
    log_info "Scripts: $total total, $missing missing, $not_exec not executable"
    if [[ "$missing" -gt 0 ]]; then log_fail "Missing scripts detected"; return 1; fi
    if [[ "$not_exec" -gt 0 ]]; then log_warn "${not_exec} script(s) not executable — use --fix to correct"; return 0; fi
    log_pass "All $total scripts present and executable"; return 0
}

# ── Check: Contract ─────────────────────────────────────────────────────────
check_contract() {
    local all_pass=true
    log_section "Check: Contract"
    for rel_path in "${CRITICAL_FILES[@]}"; do
        local fp="$PROJECT_DIR/$rel_path"
        if [[ ! -f "$fp" ]]; then log_fail "Missing critical file: $rel_path"; all_pass=false; continue; fi
        log_verbose "Found: $rel_path"
        if [[ "$rel_path" == *.json ]]; then
            if python3 -c "import json,sys; json.load(open('$fp')); sys.exit(0)" 2>/dev/null; then log_verbose "  JSON valid: $rel_path"
            else log_fail "Invalid JSON: $rel_path"; all_pass=false; fi
        fi
    done
    if [[ "$all_pass" == true ]]; then log_pass "All critical files present and valid"; return 0
    else log_fail "Critical file issues detected"; return 1; fi
}

# ── Check: Rules ────────────────────────────────────────────────────────────
check_rules() {
    log_section "Check: Rules"
    local rules_file="$PROJECT_DIR/rules/rules.json"
    if [[ ! -f "$rules_file" ]]; then log_fail "rules.json not found"; return 1; fi
    python3 -c "import json; json.load(open('$rules_file'))" 2>/dev/null || { log_fail "rules.json is not valid JSON"; return 1; }
    if command -v jq &>/dev/null; then
        for k in state_machine scoring agent_watchdog; do
            jq -e ".$k" "$rules_file" &>/dev/null || { log_fail "rules.json missing key: $k"; return 1; }
        done
        for k in states transitions; do
            jq -e ".state_machine.$k" "$rules_file" &>/dev/null || { log_fail "rules.json missing state_machine.$k"; return 1; }
        done
        log_info "Transitions: $(jq '.state_machine.transitions | length' "$rules_file")"
        log_info "Pass threshold: $(jq -r '.scoring.thresholds.pass' "$rules_file")"
    fi
    log_pass "rules.json valid with all required keys"; return 0
}

# ── Check: Cross-References (lens 4 — Agent Doc References) ────────────────
# Implements doc/health-check.md lens 4 by delegating to
# scripts/check-cross-references.sh. Invoked via bash with an explicit path
# so it behaves the same whether this script is executed or sourced.
check_references() {
    log_section "Check: Cross-References (lens 4 — Agent Doc References)"
    local xref="$SCRIPT_DIR/check-cross-references.sh"
    if [[ ! -f "$xref" ]]; then log_fail "check-cross-references.sh not found"; return 1; fi
    local args=()
    [[ "$VERBOSE" == true ]] && args+=(--verbose)
    local rc=0
    bash "$xref" "${args[@]}" || rc=$?
    if [[ "$rc" -ne 0 ]]; then
        log_fail "Broken cross-references detected (run scripts/check-cross-references.sh --verbose for detail)"
        return 1
    fi
    log_pass "All engine cross-references resolve"
    return 0
}

# ── Check: Doc Style (humanizer ship gate) ──────────────────────────────────
# Delegates to scripts/check-doc-style.sh. Invoked via bash with an explicit
# path so it behaves the same whether this script is executed or sourced.
check_docs() {
    log_section "Check: Doc Style (humanizer ship gate)"
    local dst="$SCRIPT_DIR/check-doc-style.sh"
    if [[ ! -f "$dst" ]]; then log_fail "check-doc-style.sh not found"; return 1; fi
    local args=()
    [[ "$VERBOSE" == true ]] && args+=(--verbose)
    local rc=0
    bash "$dst" "${args[@]}" || rc=$?
    if [[ "$rc" -ne 0 ]]; then
        log_fail "Doc style violations detected (run scripts/check-doc-style.sh --verbose for detail)"
        return 1
    fi
    log_pass "Shipped docs pass the style gate"
    return 0
}

check_git() {
    log_section "Check: Session"
    local session; session="$(get_session)"
    if [[ -z "$session" || "$session" == "unknown" ]]; then log_fail "Could not resolve session"; return 1; fi
    log_info "Current session: $session"
    true &>/dev/null || { log_fail "Session unavailable"; return 1; }
    log_pass "Session '$session' is safe"; return 0
}

# ── Check: Dependencies ─────────────────────────────────────────────────────
check_deps() {
    log_section "Check: Dependencies"
    local ok=true
    
    check_dep "jq" "jq" "false" || ok=false
    check_dep "bc" "bc" "true" || true
    check_dep "python3" "python3" "true" || true
    if [[ "$ok" == true ]]; then log_pass "All required dependencies available"; fi
    return 0
}

# ── Check: lean-ctx Index ──────────────────────────────────────────────────
check_index() {
    log_section "Check: lean-ctx Index"

    # lean-ctx keeps its data outside the repo by default (the stack sets
    # LEAN_CTX_DATA_DIR). Fall back to legacy in-tree .lean-ctx/ locations.
    local gd="${LEAN_CTX_DATA_DIR:-}"
    if [[ -z "$gd" ]]; then
        local c
        for c in \
            "$HOME/.local/share/opencode/lean-ctx" \
            "$PROJECT_DIR/.lean-ctx" \
            "$PROJECT_ROOT/.lean-ctx"
        do
            if [[ -d "$c" ]]; then gd="$c"; break; fi
        done
    fi

    if [[ -z "$gd" || ! -d "$gd" ]]; then
        log_info "lean-ctx index not present (optional in source checkouts; set LEAN_CTX_DATA_DIR to enable)"
        return 0
    fi

    local idx=""
    local candidate
    for candidate in "$gd/analysis.json" "$gd/index.json"; do
        if [[ -f "$candidate" ]]; then idx="$candidate"; break; fi
    done
    if [[ -z "$idx" ]]; then
        idx="$(find "$gd" -type f -print0 2>/dev/null | xargs -0 ls -t 2>/dev/null | head -1 || true)"
    fi
    if [[ -z "$idx" || ! -f "$idx" ]]; then
        log_info "lean-ctx data directory exists but has no files yet ($gd)"
        return 0
    fi

    # GNU stat first, BSD stat as fallback; keep only digits so a diagnostic
    # string can never leak into the arithmetic expansion.
    local it=""
    it=$(stat -c "%Y" "$idx" 2>/dev/null || true)
    if [[ ! "$it" =~ ^[0-9]+$ ]]; then
        it=$(stat -f "%m" "$idx" 2>/dev/null || true)
    fi
    it="${it//[^0-9]/}"
    [[ -z "$it" ]] && it=0
    local age=$(( $(date +%s) - it )); local ah=$((age / 3600))
    log_info "lean-ctx data age: ${ah}h ($((age / 60))m) — $idx"
    if [[ "$age" -gt 3600 ]]; then
        log_warn "lean-ctx data is ${ah}h old — consider re-indexing"
        if [[ "$DO_FIX" == true ]]; then
            log_info "Auto-fix: re-indexing..."
            if false; then # auto re-index unsupported; run the rag_index task manually
                log_pass "lean-ctx index refreshed"
            else
                log_warn "Auto re-index unsupported; run the rag_index task manually"
            fi
        fi
    else
        log_pass "lean-ctx data is fresh (${ah}h old)"
    fi
    return 0
}

# ── Fix Mode ────────────────────────────────────────────────────────────────
do_fix() {
    log_section "Auto-Fix Mode"; local fixes=0
    for s in "${CHECK_SCRIPTS[@]}"; do
        local fp="$SCRIPT_DIR/$s"
        if [[ -f "$fp" ]] && ! is_executable "$fp"; then chmod +x "$fp" 2>/dev/null && log_info "Made executable: $s" && fixes=$((fixes + 1)); fi
    done
    local br; br="$(get_session)"; local sd="$SESSION_DIR"
    if [[ ! -d "$sd" ]]; then mkdir -p "$sd"; log_info "Created: $sd"; fixes=$((fixes + 1)); fi
    if [[ ! -f "$sd/index.md" ]]; then
        { echo "# Session Index — Workflow State Engine"; echo ""; echo "| Session | Active | Status | Last State | Score | PR | Last Activity |"; echo "|--------|--------|--------|------------|-------|----|--------------|"; } > "$sd/index.md"
        fixes=$((fixes + 1))
    fi
    if [[ ! -f "$sd/state.md" ]]; then
        { echo "# Session State History — Workflow State Engine"; echo ""; echo "| Date | Session | State | Score | PR/Commit | Summary |"; echo "|------|--------|-------|-------|-----------|---------|"; } > "$sd/state.md"
        fixes=$((fixes + 1))
    fi
    if [[ "$fixes" -gt 0 ]]; then log_pass "Applied $fixes fix(es)"; else log_pass "Nothing to fix"; fi
}

# Check: Scheduler Heartbeat (R2-11) - fail when scheduled tasks stop reporting
check_heartbeat() {
    log_section "Check: Scheduler Heartbeat"
    local hb="${SESSION_DIR}/heartbeat.json"
    if [[ ! -f "$hb" ]]; then
        log_info "No scheduler heartbeat (${hb}) — scheduled tasks not in use"
        return 0
    fi
    local ts now age_h
    ts=$(jq -r '.timestamp // empty' "$hb" 2>/dev/null || true)
    if [[ -z "$ts" ]]; then
        log_fail "heartbeat.json present but unreadable: $hb"
        return 1
    fi
    ts=$(date -u -d "$ts" +%s 2>/dev/null || date -j -f "%Y-%m-%dT%H:%M:%SZ" "$ts" +%s 2>/dev/null || echo 0)
    now=$(date -u +%s)
    age_h=$(( (now - ts) / 3600 ))
    if (( age_h > 48 )); then
        log_fail "scheduler heartbeat is stale (${age_h}h old, threshold 48h): $hb"
        return 1
    fi
    log_pass "scheduler heartbeat fresh (${age_h}h old)"
    return 0
}

# ── Persist to session/health.json ────────────────────────────────
persist_results() {
    local session="$1" report="$2"
    # N6: compute exit code BEFORE writing health.json (was written as stale 0)
    if [[ "$HAS_CRITICAL" == true ]]; then EXIT_CODE=2; elif [[ "$HAS_WARNINGS" == true ]]; then EXIT_CODE=1; else EXIT_CODE=0; fi
    local sd="$SESSION_DIR"; mkdir -p "$sd"
    local ts; ts="$(get_timestamp)"
    echo "{\"timestamp\":\"$ts\",\"session\":\"$session\",\"check_mode\":\"$CHECK_MODE\",\"results\":$report,\"exit_code\":$EXIT_CODE,\"has_warnings\":$HAS_WARNINGS,\"has_critical\":$HAS_CRITICAL}" > "$sd/health.json"
    log_verbose "Persisted to: $sd/health.json"
}

# ── Final Report ────────────────────────────────────────────────────────────
render_report() {
    local rj="$1"
    if [[ "$OUTPUT_MODE" == "json" ]]; then echo "$rj"; return; fi
    echo -e "\n${BOLD}Health Check — Workflow State Engine${NC}\n"
    if [[ "$HAS_CRITICAL" == true ]]; then echo -e "  ${RED}[FAIL]${NC} Critical failures\n  ${BOLD}Exit:${NC} 2 (CRITICAL)"; EXIT_CODE=2
    elif [[ "$HAS_WARNINGS" == true ]]; then echo -e "  ${YELLOW}[WARN]${NC} Warnings\n  ${BOLD}Exit:${NC} 1 (WARNINGS)"; EXIT_CODE=1
    else echo -e "  ${GREEN}[PASS]${NC} All checks passed\n  ${BOLD}Exit:${NC} 0 (HEALTHY)"; EXIT_CODE=0; fi
}

main() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --help) usage ;;
            --check-all) CHECK_MODE="all"; shift ;;
            --check)
                if [[ -z "${2:-}" ]]; then echo "Error: --check requires argument"; exit 1; fi
                CHECK_MODE="$2"; shift 2 ;;
            --fix) DO_FIX=true; shift ;;
            --verbose) VERBOSE=true; shift ;;
            --output)
                if [[ -z "${2:-}" ]]; then echo "Error: --output requires argument"; exit 1; fi
                [[ "$2" != "plain" && "$2" != "json" ]] && { echo "Error: --output must be plain/json"; exit 1; }
                OUTPUT_MODE="$2"; shift 2 ;;
            *) echo "Unknown: $1"; echo "Use --help."; exit 1 ;;
        esac
    done
    local br; br="$(get_session)"
    log_section "Health Check — $br"
    log_verbose "Mode: $CHECK_MODE, Fix: $DO_FIX, Output: $OUTPUT_MODE"
    case "$CHECK_MODE" in
        all|*) check_scripts || true; check_contract || true; check_rules || true; check_references || true; check_docs || true; check_git || true; check_deps || true; check_index || true; check_heartbeat || true ;;
        scripts) check_scripts || true ;;
        contract) check_contract || true ;;
        rules) check_rules || true ;;
        references) check_references || true ;;
        docs) check_docs || true ;;
        session) check_git || true ;;
        deps) check_deps || true ;;
        index) check_index || true ;;
        heartbeat) check_heartbeat || true ;;
    esac
    if [[ "$DO_FIX" == true ]]; then do_fix; fi
    local rj
    rj=$(jq -n --arg m "$CHECK_MODE" --argjson w "$HAS_WARNINGS" --argjson c "$HAS_CRITICAL" --arg b "$br" '{check_mode:$m,session:$b,has_warnings:$w,has_critical:$c}' 2>/dev/null || echo "{\"check_mode\":\"$CHECK_MODE\",\"session\":\"$br\",\"has_warnings\":$HAS_WARNINGS,\"has_critical\":$HAS_CRITICAL}")
    persist_results "$br" "$rj"
    render_report "$rj"
    exit "$EXIT_CODE"
}

main "$@"